import {
  ArrowLeftRight,
  Check,
  Pencil,
  Plus,
  RefreshCw,
  Users,
  X,
} from 'lucide-react';
import { useState } from 'react';
import { TEAM_COLORS, TEAM_EMBLEMS } from '../engine/sports';
import {
  createId,
  formatAutoTeamName,
  isAutoGeneratedTeamName,
} from '../engine/tournamentEngine';
import type { Player, Team, Tournament } from '../types/tournament';

interface EditTeamsModalProps {
  tournament: Tournament;
  onClose: () => void;
  onSaveTeams: (updatedTeams: Team[]) => void;
}

interface DraftTeam {
  id: string;
  name: string;
  autoNameSync: boolean;
  players: Player[];
  color: string;
  emblem: string;
  seed?: number;
}

export function EditTeamsModal({
  tournament,
  onClose,
  onSaveTeams,
}: EditTeamsModalProps) {
  const isFutevolei = tournament.sport.id === 'futevolei';
  const defaultSlots = tournament.sport.id === 'futsal' ? 3 : 2;

  const [draftTeams, setDraftTeams] = useState<DraftTeam[]>(() =>
    tournament.teams.map((t) => {
      const existingPlayers =
        t.players.length > 0
          ? t.players.map((p) => ({ ...p }))
          : Array.from({ length: defaultSlots }, () => ({
              id: createId('pl'),
              name: '',
            }));
      const pNames = existingPlayers.map((p) => p.name);
      return {
        id: t.id,
        name: t.name,
        autoNameSync: isAutoGeneratedTeamName(t.name, pNames),
        players: existingPlayers,
        color: t.color,
        emblem: t.emblem,
        seed: t.seed,
      };
    }),
  );

  // Swap player composition state ("Ajustar a composição das duplas")
  const [swapSource, setSwapSource] = useState<string>('');
  const [swapTarget, setSwapTarget] = useState<string>('');
  const [swapFeedback, setSwapFeedback] = useState<string | null>(null);

  const handlePlayerNameChange = (
    teamId: string,
    playerIdx: number,
    newValue: string,
  ) => {
    setDraftTeams((prev) =>
      prev.map((team, tIdx) => {
        if (team.id !== teamId) return team;
        const nextPlayers = team.players.map((p, idx) =>
          idx === playerIdx ? { ...p, name: newValue } : p,
        );
        const nextName = team.autoNameSync
          ? formatAutoTeamName(
              nextPlayers.map((p) => p.name),
              tIdx + 1,
            )
          : team.name;
        return {
          ...team,
          players: nextPlayers,
          name: nextName,
        };
      }),
    );
  };

  const handleTeamNameChange = (teamId: string, newName: string) => {
    setDraftTeams((prev) =>
      prev.map((team) => {
        if (team.id !== teamId) return team;
        const pNames = team.players.map((p) => p.name);
        const stillAuto = isAutoGeneratedTeamName(newName, pNames);
        return {
          ...team,
          name: newName,
          autoNameSync: stillAuto,
        };
      }),
    );
  };

  const handleSyncNameFromPlayers = (teamId: string) => {
    setDraftTeams((prev) =>
      prev.map((team, tIdx) => {
        if (team.id !== teamId) return team;
        return {
          ...team,
          name: formatAutoTeamName(
            team.players.map((p) => p.name),
            tIdx + 1,
          ),
          autoNameSync: true,
        };
      }),
    );
  };

  const handleAddPlayerSlot = (teamId: string) => {
    setDraftTeams((prev) =>
      prev.map((team) =>
        team.id === teamId
          ? {
              ...team,
              players: [...team.players, { id: createId('pl'), name: '' }],
            }
          : team,
      ),
    );
  };

  const handleRemovePlayerSlot = (teamId: string, playerIdx: number) => {
    setDraftTeams((prev) =>
      prev.map((team, tIdx) => {
        if (team.id !== teamId || team.players.length <= 1) return team;
        const nextPlayers = team.players.filter((_, idx) => idx !== playerIdx);
        const nextName = team.autoNameSync
          ? formatAutoTeamName(
              nextPlayers.map((p) => p.name),
              tIdx + 1,
            )
          : team.name;
        return {
          ...team,
          players: nextPlayers,
          name: nextName,
        };
      }),
    );
  };

  const handleColorChange = (teamId: string, color: string) => {
    setDraftTeams((prev) =>
      prev.map((team) => (team.id === teamId ? { ...team, color } : team)),
    );
  };

  const handleEmblemChange = (teamId: string, emblem: string) => {
    setDraftTeams((prev) =>
      prev.map((team) => (team.id === teamId ? { ...team, emblem } : team)),
    );
  };

  const handleSwapPlayersBetweenTeams = () => {
    if (!swapSource || !swapTarget || swapSource === swapTarget) return;
    const [teamAId, idxAStr] = swapSource.split('::');
    const [teamBId, idxBStr] = swapTarget.split('::');
    const idxA = Number(idxAStr);
    const idxB = Number(idxBStr);

    const teamA = draftTeams.find((t) => t.id === teamAId);
    const teamB = draftTeams.find((t) => t.id === teamBId);
    if (!teamA || !teamB) return;

    const playerA = teamA.players[idxA];
    const playerB = teamB.players[idxB];
    if (!playerA || !playerB) return;

    setDraftTeams((prev) =>
      prev.map((team, tIdx) => {
        let nextPlayers = [...team.players];
        let changed = false;

        if (team.id === teamAId && team.id === teamBId) {
          nextPlayers[idxA] = { ...playerB };
          nextPlayers[idxB] = { ...playerA };
          changed = true;
        } else if (team.id === teamAId) {
          nextPlayers[idxA] = { ...playerB };
          changed = true;
        } else if (team.id === teamBId) {
          nextPlayers[idxB] = { ...playerA };
          changed = true;
        }

        if (!changed) return team;

        const nextName = team.autoNameSync
          ? formatAutoTeamName(
              nextPlayers.map((p) => p.name),
              tIdx + 1,
            )
          : team.name;

        return {
          ...team,
          players: nextPlayers,
          name: nextName,
        };
      }),
    );

    setSwapFeedback(
      `Composição ajustada: "${playerA.name || 'Jogador'}" ↔ "${playerB.name || 'Jogador'}"`,
    );
    setSwapSource('');
    setSwapTarget('');
    window.setTimeout(() => setSwapFeedback(null), 3000);
  };

  const handleSaveAll = (e: React.FormEvent) => {
    e.preventDefault();
    const finalTeams: Team[] = draftTeams.map((dt, idx) => {
      const cleanedPlayers = dt.players
        .map((p) => ({ ...p, name: p.name.trim() }))
        .filter((p) => Boolean(p.name));

      const finalName =
        dt.name.trim() ||
        formatAutoTeamName(
          cleanedPlayers.map((p) => p.name),
          idx + 1,
        );

      return {
        id: dt.id,
        name: finalName,
        players: cleanedPlayers,
        color: isFutevolei ? '#10b981' : dt.color,
        emblem: isFutevolei ? '' : dt.emblem,
        seed: dt.seed,
      };
    });

    onSaveTeams(finalTeams);
  };

  // Build flat list of player options for swapping composition
  const playerSlotOptions = draftTeams.flatMap((team, tIdx) =>
    team.players.map((p, pIdx) => ({
      key: `${team.id}::${pIdx}`,
      label: `Dupla ${tIdx + 1} (${team.name || `Dupla ${tIdx + 1}`}) — ${
        p.name.trim() || `Jogador ${pIdx + 1}`
      }`,
    })),
  );

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex items-end sm:items-center justify-center p-2 sm:p-4">
      <div className="w-full max-w-3xl max-h-[92vh] rounded-3xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-2xl flex flex-col overflow-hidden">
        {/* Modal Header */}
        <div className="px-5 py-4 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between gap-3 bg-slate-50/80 dark:bg-slate-900">
          <div className="flex items-center gap-2.5 min-w-0">
            <div className="w-10 h-10 rounded-xl bg-emerald-500 text-slate-950 flex items-center justify-center shrink-0">
              <Pencil className="w-5 h-5" />
            </div>
            <div className="min-w-0">
              <h2 className="text-base sm:text-lg font-extrabold text-slate-900 dark:text-white truncate">
                Editar Duplas e Jogadores
              </h2>
              <p className="text-xs text-slate-500 dark:text-slate-400 truncate">
                Altere nomes, substitua jogadores ou ajuste a composição mantendo os resultados
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Fechar edição"
            className="w-9 h-9 rounded-xl bg-slate-200/70 dark:bg-slate-800 text-slate-600 dark:text-slate-300 flex items-center justify-center shrink-0 hover:bg-slate-300/70 dark:hover:bg-slate-700 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Scrollable Content */}
        <form
          onSubmit={handleSaveAll}
          className="flex-1 overflow-y-auto p-4 sm:p-5 space-y-5"
        >
          {/* Ajustar Composição entre Duplas (Trocar Jogadores) */}
          {draftTeams.length >= 2 && (
            <section className="rounded-2xl bg-amber-50/70 dark:bg-slate-800/70 border border-amber-200/80 dark:border-slate-700 p-4 space-y-3">
              <div className="flex items-center gap-2">
                <ArrowLeftRight className="w-4 h-4 text-amber-600 dark:text-amber-400 shrink-0" />
                <h3 className="text-xs font-extrabold uppercase tracking-wider text-slate-700 dark:text-slate-200">
                  Ajustar Composição (Trocar Jogadores entre Duplas)
                </h3>
              </div>
              <div className="grid sm:grid-cols-[1fr_1fr_auto] gap-2">
                <select
                  value={swapSource}
                  onChange={(e) => setSwapSource(e.target.value)}
                  aria-label="Selecionar primeiro jogador para troca"
                  className="h-10 px-3 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 text-xs font-semibold text-slate-800 dark:text-slate-200 outline-none focus:border-emerald-500"
                >
                  <option value="">1º Jogador para trocar...</option>
                  {playerSlotOptions.map((opt) => (
                    <option key={opt.key} value={opt.key}>
                      {opt.label}
                    </option>
                  ))}
                </select>

                <select
                  value={swapTarget}
                  onChange={(e) => setSwapTarget(e.target.value)}
                  aria-label="Selecionar segundo jogador para troca"
                  className="h-10 px-3 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 text-xs font-semibold text-slate-800 dark:text-slate-200 outline-none focus:border-emerald-500"
                >
                  <option value="">2º Jogador para trocar...</option>
                  {playerSlotOptions.map((opt) => (
                    <option
                      key={opt.key}
                      value={opt.key}
                      disabled={opt.key === swapSource}
                    >
                      {opt.label}
                    </option>
                  ))}
                </select>

                <button
                  type="button"
                  disabled={!swapSource || !swapTarget || swapSource === swapTarget}
                  onClick={handleSwapPlayersBetweenTeams}
                  className="h-10 px-4 rounded-xl bg-amber-500 hover:bg-amber-400 disabled:bg-slate-200 dark:disabled:bg-slate-800 text-slate-950 disabled:text-slate-400 text-xs font-extrabold flex items-center justify-center gap-1.5 shrink-0 transition"
                >
                  <ArrowLeftRight className="w-3.5 h-3.5" />
                  Trocar
                </button>
              </div>
              {swapFeedback && (
                <p className="text-xs font-bold text-emerald-700 dark:text-emerald-400">
                  ✓ {swapFeedback}
                </p>
              )}
            </section>
          )}

          {/* Lista de Duplas Editáveis */}
          <div className="space-y-3">
            <div className="flex items-center justify-between">
              <h3 className="text-xs font-extrabold uppercase tracking-wider text-slate-500 dark:text-slate-400 flex items-center gap-1.5">
                <Users className="w-4 h-4" />
                Duplas Cadastradas ({draftTeams.length})
              </h3>
              <span className="text-[11px] font-semibold text-slate-400">
                Edite diretamente abaixo e clique em Salvar
              </span>
            </div>

            <div className="grid sm:grid-cols-2 gap-3">
              {draftTeams.map((team, idx) => (
                <div
                  key={team.id}
                  className="rounded-2xl bg-slate-50/90 dark:bg-slate-800/50 border border-slate-200 dark:border-slate-700/80 p-3.5 space-y-3"
                >
                  {/* Card Top: Index + Team Name Input */}
                  <div className="flex items-center gap-2">
                    <span className="w-7 h-7 rounded-lg bg-slate-900 dark:bg-emerald-500 text-white dark:text-slate-950 text-xs font-extrabold flex items-center justify-center shrink-0">
                      {idx + 1}
                    </span>
                    <div className="flex-1 min-w-0">
                      <label className="block text-[10px] font-extrabold uppercase tracking-wider text-slate-400 mb-0.5">
                        Nome da Dupla / Time
                      </label>
                      <div className="flex items-center gap-1">
                        <input
                          type="text"
                          value={team.name}
                          onChange={(e) =>
                            handleTeamNameChange(team.id, e.target.value)
                          }
                          placeholder={`Dupla ${idx + 1}`}
                          className="w-full h-9 px-2.5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 text-xs font-extrabold text-slate-900 dark:text-white outline-none focus:border-emerald-500"
                        />
                        {!team.autoNameSync && (
                          <button
                            type="button"
                            onClick={() => handleSyncNameFromPlayers(team.id)}
                            title="Atualizar nome automaticamente pelos jogadores"
                            className="h-9 px-2 rounded-xl bg-slate-200/80 dark:bg-slate-800 text-slate-600 dark:text-slate-300 text-[10px] font-bold flex items-center gap-1 shrink-0 hover:bg-emerald-100 dark:hover:bg-emerald-950/60"
                          >
                            <RefreshCw className="w-3 h-3" />
                          </button>
                        )}
                      </div>
                    </div>
                  </div>

                  {/* Players Inputs */}
                  <div className="space-y-1.5">
                    <div className="flex items-center justify-between">
                      <span className="text-[10px] font-extrabold uppercase tracking-wider text-slate-400">
                        Jogadores da Dupla
                      </span>
                      <button
                        type="button"
                        onClick={() => handleAddPlayerSlot(team.id)}
                        className="text-[11px] font-bold text-emerald-600 dark:text-emerald-400 flex items-center gap-0.5 hover:underline"
                      >
                        <Plus className="w-3 h-3" /> Jogador
                      </button>
                    </div>

                    <div className="space-y-1.5">
                      {team.players.map((player, pIdx) => (
                        <div key={player.id || pIdx} className="flex items-center gap-1.5">
                          <input
                            type="text"
                            value={player.name}
                            onChange={(e) =>
                              handlePlayerNameChange(team.id, pIdx, e.target.value)
                            }
                            placeholder={`Jogador ${pIdx + 1}`}
                            className="flex-1 h-9 px-2.5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 text-xs font-semibold text-slate-800 dark:text-slate-100 outline-none focus:border-emerald-500"
                          />
                          {team.players.length > 1 && (
                            <button
                              type="button"
                              onClick={() => handleRemovePlayerSlot(team.id, pIdx)}
                              title="Remover jogador"
                              className="w-8 h-9 rounded-xl bg-slate-200/60 dark:bg-slate-800 text-slate-400 hover:text-rose-500 flex items-center justify-center shrink-0"
                            >
                              <X className="w-3.5 h-3.5" />
                            </button>
                          )}
                        </div>
                      ))}
                    </div>
                  </div>

                  {/* Color & Emblem if not Futevôlei */}
                  {!isFutevolei && (
                    <div className="pt-1 border-t border-slate-200/70 dark:border-slate-700/60 flex items-center justify-between gap-2 flex-wrap">
                      <div className="flex items-center gap-1">
                        {TEAM_COLORS.slice(0, 6).map((c) => (
                          <button
                            key={c}
                            type="button"
                            onClick={() => handleColorChange(team.id, c)}
                            className={`w-5 h-5 rounded-full border ${
                              team.color === c
                                ? 'border-slate-900 dark:border-white scale-110'
                                : 'border-transparent'
                            }`}
                            style={{ backgroundColor: c }}
                          />
                        ))}
                      </div>
                      <div className="flex items-center gap-1">
                        {TEAM_EMBLEMS.slice(0, 5).map((em) => (
                          <button
                            key={em}
                            type="button"
                            onClick={() => handleEmblemChange(team.id, em)}
                            className={`w-6 h-6 rounded-lg text-xs flex items-center justify-center border ${
                              team.emblem === em
                                ? 'border-emerald-500 bg-emerald-50 dark:bg-emerald-950'
                                : 'border-slate-200 dark:border-slate-700'
                            }`}
                          >
                            {em}
                          </button>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>

          {/* Modal Footer */}
          <div className="pt-3 border-t border-slate-200 dark:border-slate-800 flex items-center justify-end gap-2.5 sticky bottom-0 bg-white dark:bg-slate-900 pb-1">
            <button
              type="button"
              onClick={onClose}
              className="h-11 px-4 rounded-2xl bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 font-bold text-xs transition"
            >
              Cancelar
            </button>
            <button
              type="submit"
              className="h-11 px-5 rounded-2xl bg-emerald-600 hover:bg-emerald-500 text-white font-extrabold text-xs sm:text-sm flex items-center gap-2 shadow-lg shadow-emerald-600/25 active:scale-[0.98] transition"
            >
              <Check className="w-4 h-4" />
              Salvar Alterações
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
